    def get_homotopic_belief(self, obs_hsig, gmm_hsigs):
        """Computing only over the h-sigs that are considered in the GMM to speed things up"""
        if obs_hsig.sig == ():
            #if there is no homotopic information yet, initialise uniform prior
            p_normalised = [1 / len(gmm_hsigs)
                            for sig in gmm_hsigs
                            ]
        
        else:
            obs_hsig_len = len(obs_hsig.sig)

            hsig_probs = {
                sig : self.get_hsig_prob(sig) 
                if sig.sig[0:obs_hsig_len] == obs_hsig.sig 
                else 0.0
                for sig in gmm_hsigs
            }

            nrml_factor = sum(
                [prob for prob in hsig_probs.values()]
            )

            if nrml_factor > 0:
                p_normalised = [
                    prob / nrml_factor
                    for sig, prob in hsig_probs.items()
                ]
            else:
                p_normalised = [
                    0.0
                    for sig in hsig_probs.keys()
                ]

        hsigs = list(map(HSignature.as_string, gmm_hsigs))
        prob_dataframe = pd.DataFrame(p_normalised, index = hsigs, columns=['probs'])

        return prob_dataframe
    

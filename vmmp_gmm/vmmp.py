class VMMP:
    def __init__(self, root_trns_prob, wrd_len_prob_dict=None):
        self.root = Node(HSignature(()), root_trns_prob)
        # root of tree should be the identity character
        self.node_dict = {() : self.root}
        self.alphabet = list(root_trns_prob.keys())
        self.wrd_len_prob_dict = wrd_len_prob_dict

    def add_node(self, node_sig, trns_prob, parent):
        """ Add new node to the VMMP.

        Inputs
        --------
        node : HSignature
            HSignature of the new node, signature corresponding to suffix
        parent : tuple
            tuple identifying parent suffix node, i.e. HSignature.sig
        trns_prob : dictionary
            dictionary of probabilities that this node comes before single characters
            in given alphabet. keys are characters, values are probabilities e.g. found by
            calc_transition_prob(character, node)
        """
        if node_sig.sig in self.get_all_nodes():
            return "Node already in tree"

        new_node = Node(node_sig, trns_prob, parent)
        self.node_dict[new_node.sig.sig] = new_node
        self.node_dict[parent].add_child(new_node)

        return new_node

    def get_node_obj(self, node):
        '''Returns a node object specified by user.'''
        if isinstance(node, (tuple)): 
            node_key = node
        elif isinstance(node, (HSignature)):
            node_key = node.sig
        else:
            print('input should be string or HSignature only')
        
        try:
            return self.node_dict[node_key]
        except KeyError:
            print("Node doesn't exist")
    
    def get_all_nodes(self):
        '''Returns all node objects in the vmmp instance.'''
        return list(self.node_dict.keys())

    def get_leaves(self):
        leaves = []
        def check_node_for_leaf(node):
            if not node.children:
                leaves.append(node)
                return
            else:
                for child in node.children:
                    child_node = self.get_node_obj(child)
                    check_node_for_leaf(child_node)
        check_node_for_leaf(self.root)
        return leaves

    def get_trns_prob(self, node, character):
        '''
        Inputs
        --------
        node : tuple
            tuple of HSignature identifying the node in  vmmp, i.e. HSignature.sig
        
        character : tuple
            character in alphabet being queried.

        Returns
        --------
        Returns transition probability from node to character in alphabet nodes'''
        if isinstance(node, (tuple)): 
            node_key = node
        elif isinstance(node, (HSignature)):
            node_key = node.sig
        else:
            print('inputs should be tuple or HSignature object only')

        # print('debugging trns_prob call', node_key, character)
        return self.node_dict[node_key].trns_prob[character]
    
    def get_hsig_length_prob(self, data):
        len_hist = Counter([len(x.sig) for x in data])
        data_len = len(data)
        len_prob_dict = len_hist
        len_prob_dict = {k: v / data_len for k, v in len_prob_dict.items()}
        self.wrd_len_prob_dict = len_prob_dict

    def get_hsig_prob(self, h_sig):
        '''Returns the probability of a word being generated by this VMMP.
        Product of suffixes along a path through the graph.
        '''
        if isinstance(h_sig, (HSignature)):
            sig = h_sig.sig
        if isinstance(h_sig, (tuple)):
            sig = h_sig
        prob = 1.0
        # current_sfx = self.root
        for i in range(len(sig)):
            sfx_list = vmmp_utils.get_all_suffixes(HSignature(sig[:i]))
            sfx_list = sorted(sfx_list, key= lambda x: -len(x.sig))
            for sfx in sfx_list:
                if sfx.sig in self.get_all_nodes():
                    # print('tuple or int', (h_sig.sig[i],))
                    prob *= self.get_trns_prob(sfx, (sig[i],))
                    # print(sfx, h_sig.sig[i], h_sig.sig[:i+1], prob)
                    break
        return prob
    
    def generate_hsig(self):
        ''' Generate a HSignature of desired length given transition probabilities of
        nodes in the VMMP.'''
        word = ()
        wrd_lens = list(self.wrd_len_prob_dict.keys())
        wrd_len_probs = list(self.wrd_len_prob_dict.values())
        wrd_len_roll = np.random.multinomial(1, wrd_len_probs, size=1)
        for l, r in zip(wrd_lens, wrd_len_roll[0]):
            if r == 1:
                wrd_len = l
        i = 0
        while len(word) < wrd_len:
            # print('generating word', len(word), 'out of', wrd_len, 'word is:', word)
            sfx_list = vmmp_utils.get_all_suffixes(HSignature(word[:i]))
            # print('generating word', [x.sig for x in sfx_list])
            sfx_list = sorted(sfx_list, key=lambda x: -len(x.sig))
            for sfx in sfx_list:
                sfx_sig = sfx.sig
                # print(self.get_all_nodes())
                # print('here', sfx_sig)
                if sfx_sig in self.get_all_nodes():
                    # print('here')
                    sfx_node = self.get_node_obj(sfx_sig)
                    probs = list(sfx_node.trns_prob.values())
                    roll = np.random.multinomial(1, probs, size=1)
                    for a, r in zip(self.alphabet, roll[0]):
                        if r == 1:
                            word += a
                    # word += [a for a, r in zip(alphabet, roll[0]) if r == 1][0]
                    # print(word)
                    i+=1
                    break
        return HSignature(word)

